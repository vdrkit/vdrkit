function compose(args, opts = {}) {
  assertThrowaway(project, dir);
  const all = ['compose', '-p', project, '--project-directory', dir, '-f', join(repo, 'docker-compose.yml'), '-f', join(repo, 'docker', 'smoke', 'compose.smoke.yml'), ...args];
  const r = spawnSync('docker', all, { encoding: 'utf8', env: dockerEnv, maxBuffer: 64 * 1024 * 1024, ...opts });
  if (r.status !== 0 && !opts.allowFail) throw new Error(`docker ${all.join(' ')} failed (${r.status}):\n${r.stdout}\n${r.stderr}`);
  return r.stdout ?? '';
}

function prepare() {
  assertThrowaway(project, dir);
  mkdirSync(join(dir, 'docker'), { recursive: true });
  cpSync(join(repo, 'Caddyfile'), join(dir, 'Caddyfile'));
  for (const sub of ['postgres-init', 'backup']) cpSync(join(repo, 'docker', sub), join(dir, 'docker', sub), { recursive: true });
  const ssl = (...a) => execFileSync('openssl', a, { cwd: dir, stdio: 'pipe' });
  ssl('req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-keyout', 'ca-key.pem', '-out', 'ca.pem', '-days', '2', '-subj', '/CN=VDRkit smoke test CA');
  ssl('req', '-newkey', 'rsa:2048', '-nodes', '-keyout', 'mailpit-key.pem', '-out', 'mailpit.csr', '-subj', '/CN=mailpit');
  writeFileSync(join(dir, 'san.ext'), 'subjectAltName=DNS:mailpit\nextendedKeyUsage=serverAuth\n');
  ssl('x509', '-req', '-in', 'mailpit.csr', '-CA', 'ca.pem', '-CAkey', 'ca-key.pem', '-CAcreateserial', '-out', 'mailpit.pem', '-days', '2', '-extfile', 'san.ext');
  const hex = () => randomBytes(24).toString('hex');
  const image = env.VDRKIT_IMAGE ?? 'vdrkit';
  const tag = env.VDRKIT_TAG ?? 'smoke';
  const profiles = [];
  if (!external) profiles.push('postgres');
  if (clamav) profiles.push('clamav');
  const lines = [
    '# Generated by docker/smoke/smoke.mjs: throwaway values for one test run.',
    `VDRKIT_IMAGE=${image}`, `VDRKIT_TAG=${tag}`,
    `COMPOSE_PROFILES=${profiles.join(',')}`,
  ];
  if (external) {
    lines.push(
      `DATABASE_URL=${env.SMOKE_DATABASE_URL}`,
      `QUEUE_DATABASE_URL=${env.SMOKE_QUEUE_DATABASE_URL}`,
      `MIGRATION_DATABASE_URL=${env.SMOKE_MIGRATION_DATABASE_URL}`,
    );
  }
  if (!clamav) lines.push('CLAMAV_HOST=');
  lines.push(
    'SITE_ADDRESS=localhost', `PUBLIC_URL=${base}`,
    'BIND_ADDRESS=127.0.0.1', `HTTP_PORT=${httpPort}`, `HTTPS_PORT=${httpsPort}`,
    `POSTGRES_PASSWORD=${hex()}`, `VDRKIT_OWNER_PASSWORD=${hex()}`, `VDRKIT_APP_PASSWORD=${hex()}`, `VDRKIT_QUEUE_PASSWORD=${hex()}`,
    'STORAGE_DRIVER=local',
    `VDRKIT_MASTER_KEY=${randomBytes(32).toString('base64')}`,
    `BETTER_AUTH_SECRET=${randomBytes(32).toString('base64')}`,
    'SMTP_HOST=', 'SMTP_URL=', 'SMTP_USER=', 'SMTP_PASSWORD=', 'MAIL_FROM=',
    '',
  );
  writeFileSync(join(dir, '.env'), lines.join('\n'));
}

async function until(what, fn, timeoutMs, everyMs = 1000) {
  const end = Date.now() + timeoutMs;
  let last;
  while (Date.now() < end) {
    try {
      const v = await fn();
      if (v) return v;
    } catch (e) {
      last = e;
    }
    await sleep(everyMs);
  }
  throw new Error(`Timed out waiting for ${what}${last ? `: ${last.message}` : ''}`);
}

function pdf() {
  const objs = [];
  const add = (s) => { objs.push(s); return objs.length; };
  const font = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  const pagesId = objs.length + 1 + 4; // filled below
  const pageIds = [];
  for (const n of [1, 2]) {
    const text = `BT /F1 24 Tf 72 720 Td (VDRkit smoke test, page ${n}) Tj ET`;
    const content = add(`<< /Length ${text.length} >>\nstream\n${text}\nendstream`);
    pageIds.push(add(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 612 792] /Contents ${content} 0 R /Resources << /Font << /F1 ${font} 0 R >> >> >>`));
  }
  const pages = add(`<< /Type /Pages /Kids [${pageIds.map((i) => `${i} 0 R`).join(' ')}] /Count ${pageIds.length} >>`);
  if (pages !== pagesId) throw new Error('PDF object numbering');
  const catalog = add(`<< /Type /Catalog /Pages ${pages} 0 R >>`);
  let out = '%PDF-1.7\n';
  const offsets = [];
  objs.forEach((o, i) => { offsets.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  out += `trailer\n<< /Size ${objs.length + 1} /Root ${catalog} 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

const rtf = () => Buffer.from('{\\rtf1\\ansi\\deff0{\\fonttbl{\\f0 Helvetica;}}\\f0\\fs28 VDRkit smoke test: this file was converted to PDF by Gotenberg.\\par}\n', 'latin1');

/** RFC 6238, SHA-1, 30 s, 6 digits */
function totp(secret, at = Date.now()) {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
  let bits = '';
  for (const ch of secret.replace(/[\s=]/g, '').toUpperCase()) bits += alphabet.indexOf(ch).toString(2).padStart(5, '0');
  const key = Buffer.from(bits.match(/.{8}/g).map((b) => parseInt(b, 2)));
  const counter = Buffer.alloc(8);
  counter.writeBigUInt64BE(BigInt(Math.floor(at / 30_000)));
  const h = createHmac('sha1', key).update(counter).digest();
  const o = h[h.length - 1] & 0xf;
  const n = ((h[o] & 0x7f) << 24) | (h[o + 1] << 16) | (h[o + 2] << 8) | h[o + 3];
  return String(n % 1_000_000).padStart(6, '0');
}

async function mail(to, subject, since) {
  return until(`an email "${subject}" to ${to}`, async () => {
    const res = await fetch(`${mailApi}/search?query=${encodeURIComponent(`to:"${to}"`)}`);
    const { messages = [] } = await res.json();
    const m = messages.find((x) => subject.test(x.Subject) && new Date(x.Created).getTime() >= since);
    if (!m) return null;
    return (await fetch(`${mailApi}/message/${m.ID}`)).json();
  }, 60_000, 500);
}

async function main() {
  const t0 = Date.now();
  prepare();
  step('install folder prepared', { dir });

  const upStarted = Date.now();
  compose(['up', '-d']);
  results.timings.composeUpReturnedMs = Date.now() - upStarted;
  const api = await pwRequest.newContext({ baseURL: base, ignoreHTTPSErrors: true, extraHTTPHeaders: { origin: base } });
  await until('the API through Caddy', async () => (await api.get('/v1/health')).status() === 200, 300_000);
  results.timings.apiAnsweredMs = Date.now() - upStarted;
  await until('the web front end through Caddy', async () => {
    const r = await api.get('/sign-in');
    return r.status() === 200 && new URL(r.url()).pathname === '/setup' && (await r.text()).includes('<html');
  }, 120_000);
  results.timings.webAnsweredMs = Date.now() - upStarted;
  step('stack answers on HTTPS through Caddy', results.timings);

  const migrateLog = compose(['logs', '--no-color', 'migrate']);
  const appliedLines = migrateLog.split('\n').filter((l) => /Migration \S+ applied in \d+ ms/.test(l));
  if (!/Database is up to date/.test(migrateLog) || appliedLines.length === 0) throw new Error(`migrate did not finish:\n${migrateLog}`);
  step('migrate applied every migration, one line each', { migrations: appliedLines.length });

  const users = {};
  for (const svc of ['api', 'worker', 'web']) users[svc] = compose(['exec', '-T', svc, 'id', '-un']).trim();
  if (Object.values(users).some((u) => u !== 'node')) throw new Error(`Not the unprivileged user: ${JSON.stringify(users)}`);
  step('services run as the unprivileged user', users);
  // names only, never values
  const envNames = (svc) => new Set(compose(['exec', '-T', svc, 'node', '-e',
    'for (const [k, v] of Object.entries(process.env)) if (v) console.log(k)']).trim().split(/\r?\n/));
  const forbidden = {
    api: ['POSTGRES_PASSWORD', 'VDRKIT_OWNER_PASSWORD', 'VDRKIT_APP_PASSWORD', 'VDRKIT_QUEUE_PASSWORD', 'MIGRATION_DATABASE_URL'],
    worker: ['POSTGRES_PASSWORD', 'VDRKIT_OWNER_PASSWORD', 'VDRKIT_APP_PASSWORD', 'VDRKIT_QUEUE_PASSWORD', 'MIGRATION_DATABASE_URL', 'BETTER_AUTH_SECRET'],
    web: ['POSTGRES_PASSWORD', 'VDRKIT_OWNER_PASSWORD', 'VDRKIT_APP_PASSWORD', 'VDRKIT_QUEUE_PASSWORD', 'MIGRATION_DATABASE_URL',
      'BETTER_AUTH_SECRET', 'VDRKIT_MASTER_KEY', 'DATABASE_URL', 'QUEUE_DATABASE_URL', 'S3_SECRET_ACCESS_KEY', 'SMTP_PASSWORD'],
  };
  for (const [svc, names] of Object.entries(forbidden)) {
    const has = envNames(svc);
    const leaked = names.filter((n) => has.has(n));
    if (leaked.length) throw new Error(`${svc} holds ${leaked.join(', ')}`);
  }
  const reach = compose(['exec', '-T', 'web', 'node', '-e',
    "require('net').connect(5432, 'postgres').on('connect', () => { console.log('reached'); process.exit(0); }).on('error', (e) => { console.log(e.code); process.exit(0); })"]).trim();
  if (reach === 'reached') throw new Error('The web container reaches Postgres');
  step('secrets per service; web cannot reach Postgres', { webToPostgres: reach });
  const fonts = compose(['exec', '-T', 'worker', 'fc-list']).trim().split(/\r?\n/).filter(Boolean).length;
  if (fonts === 0) throw new Error('No fonts in the image: watermarks would show boxes instead of letters');
  step('fonts for the watermark', { fonts });

  const code = await until('the setup code in the API log', async () => /Setup code: ([A-Z0-9]{4}-[A-Z0-9]{4})/.exec(compose(['logs', '--no-color', 'api']))?.[1], 60_000);
  const open = await (await api.get('/v1/setup')).json();
  if (!open.open) throw new Error('Setup is not open on a fresh installation');
  const unlock = await api.post('/v1/setup/unlock', { data: { code } });
  if (!unlock.ok()) throw new Error(`unlock: ${unlock.status()} ${await unlock.text()}`);
  const { token, header } = await unlock.json();
  const call = async (method, path, data) => {
    const opts = { method, headers: { [header]: token } };
    if (data !== undefined) opts.data = data;
    const r = await api.fetch(path, opts);
    if (!r.ok()) throw new Error(`${method} ${path}: ${r.status()} ${await r.text()}`);
    return r.status() === 204 ? null : r.json();
  };
  // ClamAV needs time for signatures
  const checks = await until('the setup checks (database, storage, conversion, virus scanner)', async () => {
    const c = await call('GET', '/v1/setup/checks');
    const by = Object.fromEntries(c.items.map((i) => [i.key, i.status]));
    const scannerOk = clamav ? by.virus_scanner === 'ok' : by.virus_scanner === 'warning';
    return by.database === 'ok' && by.storage === 'ok' && by.conversion === 'ok' && scannerOk ? c : null;
  }, 600_000, 5000);
  step('setup checks', Object.fromEntries(checks.items.map((i) => [i.key, i.status])));
  await call('PUT', '/v1/setup/admin', admin);
  await call('PUT', '/v1/setup/organisation', { name: 'Grenlodge Partners' });
  await call('PUT', '/v1/setup/mail', { host: 'mailpit', port: 1025, security: 'starttls', user: null, fromAddress: 'dataroom@smoke.example' });
  const sentAt = Date.now() - 2000;
  const test = await call('POST', '/v1/setup/test-email', { timeZone: 'Africa/Johannesburg' });
  if (test.status !== 'accepted') throw new Error(`Test email not accepted: ${JSON.stringify(test)}`);
  await mail(admin.email, /./, sentAt);
  const done = await call('POST', '/v1/setup/finish');
  step('first-run setup finished through the API, test email received by Mailpit over STARTTLS', { personId: done.personId });

  // without the client IP one visitor rate-limits everyone
  const webIp = execFileSync('docker', ['inspect', '-f', '{{range .NetworkSettings.Networks}}{{.IPAddress}} {{end}}',
    compose(['ps', '-q', 'web']).trim()], { encoding: 'utf8' }).trim().split(/\s+/);
  await api.get('/invite/smoke-address-check');
  const inviteLine = await until('the invitation lookup in the API log', async () => compose(['logs', '--no-color', 'api']).split('\n')
    .reverse().find((l) => l.includes('/v1/public/invitations/smoke-address-check') && l.includes('remoteAddress')), 30_000);
  const remote = /"remoteAddress":"([^"]+)"/.exec(inviteLine)?.[1];
  if (!remote || webIp.includes(remote)) throw new Error(`The API saw the web container (${remote}) instead of the visitor`);
  step('server-rendered calls carry the visitor address', { web: webIp.join(' '), apiSaw: remote });

  const browser = await chromium.launch();
  const context = await browser.newContext({ ignoreHTTPSErrors: true, baseURL: base, viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  try {
    await page.goto('/sign-in');
    await page.locator('#f-email').fill(admin.email);
    const since = Date.now() - 2000;
    await page.getByRole('button', { name: 'Email me a link and a code' }).click();
    await page.getByRole('heading', { name: 'Check your email' }).waitFor();
    const m = await mail(admin.email, /\d{3} ?\d{3}/, since);
    const signInCode = /(\d{3}) ?(\d{3})/.exec(m.Subject).slice(1).join('');
    const typeCode = async (c) => {
      await page.locator('.card .code input').first().click();
      await page.keyboard.type(c);
    };
    await typeCode(signInCode);
    await page.getByRole('button', { name: 'Continue' }).click();
    const twoFactor = page.getByRole('heading', { name: 'Set up two-factor sign-in' });
    const leftSignIn = (u) => !u.pathname.startsWith('/sign-in') || u.pathname.includes('two-factor');
    await page.waitForURL(leftSignIn, { timeout: 30_000 }).catch(() => {});
    let askedForTwoFactor = await twoFactor.isVisible().catch(() => false);
    if (!askedForTwoFactor) askedForTwoFactor = await twoFactor.waitFor({ timeout: 5000 }).then(() => true, () => false);
    if (askedForTwoFactor) {
      const key = (await page.getByTestId('manual-key').textContent()).replace(/\s/g, '');
      await typeCode(totp(key));
      await page.getByRole('button', { name: 'Turn on two-factor sign-in' }).click();
      step('two-factor set up with an authenticator code');
    }
    await page.waitForURL((u) => !u.pathname.startsWith('/sign-in'), { timeout: 30_000 });
    const me = await page.request.get('/v1/me/workspaces');
    if (!me.ok()) throw new Error(`Signed in, but /v1/me/workspaces answered ${me.status()}`);
    const cookies = (await context.cookies()).map((c) => c.name);
    step('signed in through Caddy with the emailed code', { landedOn: new URL(page.url()).pathname, cookies: cookies.filter((c) => c.includes('session')) });

    const post = async (path, data, headers = {}) => {
      const r = await page.request.post(path, { data, headers: { origin: base, ...headers } });
      if (!r.ok()) throw new Error(`POST ${path}: ${r.status()} ${await r.text()}`);
      return r.json();
    };
    const room = await post('/v1/workspaces', { name: 'Smoke Test Room', start: 'empty', topFolders: ['Finance'], timeZone: 'Africa/Johannesburg' });
    const list = await page.request.get(`/v1/workspaces/${room.id}/nodes`);
    const finance = (await list.json()).items.find((n) => n.kind === 'folder' && n.name === 'Finance');
    if (!finance) throw new Error(`No Finance folder in the new room: ${await list.text()}`);
    step('room created', { id: room.id, folder: finance.indexNumber });

    const viewed = {};
    for (const [name, bytes, mime] of [['Smoke test.pdf', pdf(), 'application/pdf'], ['Smoke test letter.rtf', rtf(), 'application/rtf']]) {
      const s = await post(`/v1/workspaces/${room.id}/upload-sessions`, {
        targetFolderId: finance.id, path: name, size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), mime,
      });
      if (s.method !== 'direct') throw new Error(`Expected a direct upload on local storage, got ${s.method}`);
      const put = await page.request.put(s.uploadUrl, { data: bytes, headers: { origin: base, 'content-type': 'application/octet-stream' } });
      if (put.status() !== 204) throw new Error(`PUT ${s.uploadUrl}: ${put.status()} ${await put.text()}`);
      const doneUpload = await post(`/v1/workspaces/${room.id}/upload-sessions/${s.id}/complete`, {});
      const t = Date.now();
      await until(`page 1 of ${name} in the viewer`, async () => {
        await page.goto(`/rooms/${room.id}/view/${doneUpload.nodeId}`);
        const img = page.locator('#p1 img');
        await img.waitFor({ state: 'visible', timeout: 5000 });
        return img.evaluate((el) => el.complete && el.naturalWidth > 0);
      }, 180_000, 2000);
      viewed[name] = { processedAndShownMs: Date.now() - t };
      await page.screenshot({ path: join(dir, `${name.replace(/\W+/g, '-')}.png`) });
    }
    step('uploaded and viewed (PDF through MuPDF, RTF through Gotenberg then MuPDF)', viewed);
    // must be refused before the body is read
    const apiMem = () => {
      const raw = execFileSync('docker', ['stats', '--no-stream', '--format', '{{.MemUsage}}', compose(['ps', '-q', 'api']).trim()], { encoding: 'utf8' });
      const [, n, unit] = /([\d.]+)\s*([KMG]i?B)/.exec(raw);
      return Number(n) * ({ KiB: 1 / 1024, MiB: 1, GiB: 1024, kB: 1 / 1000, MB: 1, GB: 1000 }[unit] ?? 1);
    };
    const before = apiMem();
    const big = Buffer.alloc(256 * 1024 * 1024, 1);
    const ghost = `/v1/workspaces/${room.id}/upload-sessions/${randomUUID()}/content`;
    const putBig = () => page.request
      .put(ghost, { data: big, timeout: 120_000, headers: { origin: base, 'content-type': 'application/octet-stream' } })
      .then((r) => r.status(), (e) => `closed (${e.message.split('\n')[0]})`);
    const answers = await Promise.all([putBig(), putBig()]);
    const after = apiMem();
    if (answers.some((a) => a !== 404 && !String(a).startsWith('closed'))) throw new Error(`Large PUT to a missing session answered ${answers}`);
    if (after - before > 200) throw new Error(`API memory grew by ${Math.round(after - before)} MiB on two refused 256 MB uploads`);
    step('large uploads to a missing session refused without buffering', { answers, apiMiBBefore: Math.round(before), apiMiBAfter: Math.round(after) });

  } finally {
    await browser.close();
    await api.dispose();
  }

  const containers = compose(['ps', '-a', '--format', 'json']).trim().split('\n').filter(Boolean);
  const health = {};
  for (const c of JSON.parse(`[${containers.join(',')}]`)) {
    let state = c.State;
    if (c.Health) state += ` (${c.Health})`;
    if (c.State === 'exited') state += ` exit ${c.ExitCode}`;
    health[c.Service] = state;
  }
  step('container states', health);
  const unhealthy = Object.entries(health).filter(([svc, st]) => svc !== 'migrate' && !/running \(healthy\)|running$/.test(st));
  if (unhealthy.length) throw new Error(`Not healthy: ${JSON.stringify(Object.fromEntries(unhealthy))}`);
  const limits = {};
  for (const svc of ['api', 'worker', 'web']) {
    const id = compose(['ps', '-q', svc]).trim();
    const bytes = execFileSync('docker', ['inspect', '-f', '{{.HostConfig.Memory}}', id], { encoding: 'utf8' }).trim();
    limits[svc] = Number(bytes) / 2 ** 20;
  }
  if (Object.values(limits).some((m) => !(m > 0))) throw new Error(`Missing memory limit: ${JSON.stringify(limits)}`);
  step('memory limits (MiB)', limits);

  results.timings.totalMs = Date.now() - t0;
}

let failed = false;
try {
  await main();
} catch (err) {
  failed = true;
  console.error(`[smoke] FAILED: ${err.stack ?? err}`);
  try {
    console.error(compose(['logs', '--no-color', '--tail', '80'], { allowFail: true }));
  } catch {}
} finally {
  if (env.SMOKE_KEEP === '1') log(`stack left running (SMOKE_KEEP=1): docker compose -p ${project} --project-directory ${dir} -f docker-compose.yml -f docker/smoke/compose.smoke.yml down -v`);
  else if (isThrowaway(project, dir)) {
    compose(['down', '-v', '--remove-orphans'], { allowFail: true });
    log('stack and its volumes removed');
    for (const f of ['.env', 'ca-key.pem', 'mailpit-key.pem']) rmSync(join(dir, f), { force: true });
    log('throwaway .env and private keys deleted');
  }
  console.log(JSON.stringify({ ok: !failed, ...results }, null, 2));
  process.exit(failed ? 1 : 0);
}
