import { execFileSync, execSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const apiDir = resolve(here, '../src/api');
const jsonPath = resolve(apiDir, 'openapi.json');
const typesPath = resolve(apiDir, 'schema.d.ts');

if (!process.argv.includes('--no-build')) {
  // string form so Windows finds pnpm.cmd
  for (const pkg of ['@vdrkit/core', '@vdrkit/server']) execSync(`pnpm --filter ${pkg} build`, { cwd: root, stdio: 'inherit' });
}
execFileSync(process.execPath, [resolve(root, 'apps/server/scripts/export-openapi.mjs'), jsonPath], { cwd: root, stdio: 'inherit' });

const doc = JSON.parse(await readFile(jsonPath, 'utf8'));
const ast = await openapiTS(doc, { alphabetize: false, exportType: false });
const header =
  '/**\n * GENERATED by apps/dataroom/scripts/generate-api-types.mjs from apps/server (openapi-typescript).\n' +
  ' * Do not edit by hand. Regenerate with: corepack pnpm@9.15.4 --filter @vdrkit/dataroom api:types\n */\n\n';
await writeFile(typesPath, header + astToString(ast));
console.log(`Wrote ${typesPath}`);
